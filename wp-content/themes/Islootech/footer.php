            progressCircle3.style.background = `conic-gradient(rgb(0 0 0 / 0%) ${progress}deg, rgb(236, 49, 14, 0.41) ${progress}deg)`;

            const angle = (progress * Math.PI) / 180; // Convert degrees to radians
            const x = 50 + 45 * Math.cos(angle - Math.PI / 2); // Calculate x-coordinate
            const y = 50 + 45 * Math.sin(angle - Math.PI / 2); // Calculate y-coordinate
            dot3.style.transform = `translate(-50%, -50%) translate(${x}px, ${y}px)`;
        }
    });

    audio3.addEventListener('ended', () => {
        isPlaying3 = false;
